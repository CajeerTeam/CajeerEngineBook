"""Actual Studio drag/drop, form alternative and publication via a PHP server."""
import os
import re
import socket
import subprocess
import tempfile
import time
from pathlib import Path
from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[1]

def check(condition, label):
    if not condition:
        raise AssertionError(label)
    print('PASS ' + label, flush=True)

with tempfile.TemporaryDirectory() as work:
    with socket.socket() as sock:
        sock.bind(('127.0.0.1', 0))
        port = sock.getsockname()[1]
    base = f'http://127.0.0.1:{port}'
    password = 'tree-browser-password'
    password_hash = subprocess.check_output(['php', '-r', 'echo password_hash("tree-browser-password",PASSWORD_DEFAULT);'], text=True)
    env = dict(os.environ, BOOK_DATA_DIR=str(Path(work) / 'data'), BOOK_ADMIN_HASH=password_hash, BOOK_SECURE_COOKIE='0')
    seed = r'''require "core/Update/OperationFiles.php";require "src/BookStore.php";$s=new CajeerBook\BookStore(getenv("BOOK_DATA_DIR"));$s->change(function(&$db){$p=$db["pages"]["handbook/1.0/welcome"]["draft"];$p["title"]="Child";$p["order"]=11;$db["pages"]["handbook/1.0/welcome/child"]=["draft"=>$p,"published"=>$p,"revision"=>1];});'''
    subprocess.run(['php', '-r', seed], cwd=ROOT, env=env, check=True)
    with open(Path(work) / 'server.log', 'w+') as log:
        server = subprocess.Popen(['php', '-S', f'127.0.0.1:{port}', '-t', 'public', 'public/router.php'], cwd=ROOT, env=env, stdout=log, stderr=log)
        try:
            for _ in range(50):
                try:
                    with socket.create_connection(('127.0.0.1', port), timeout=.2):
                        break
                except OSError:
                    time.sleep(.1)
            with sync_playwright() as pw:
                launch = {'headless': True}
                if os.environ.get('BOOK_CHROMIUM_EXECUTABLE'):
                    launch.update(executable_path=os.environ['BOOK_CHROMIUM_EXECUTABLE'], args=['--no-sandbox'])
                browser = pw.chromium.launch(**launch)
                context = browser.new_context(http_credentials={'username': 'admin', 'password': password})
                page = context.new_page()
                page.set_default_timeout(10000)
                errors = []
                page.on('pageerror', lambda err: errors.append(str(err)))
                # Local-only option for sandboxes that block loopback navigation. Load
                # real server-rendered markup and forward the real form payload to PHP.
                # Normal CI navigates and submits forms in the browser directly.
                bridged = os.environ.get('BOOK_TEST_BROWSER_TRANSPORT') == '1'
                api = pw.request.new_context(http_credentials={'username': 'admin', 'password': password})
                def load_tree(url):
                    response = api.get(url)
                    assert response.ok, response.text()
                    markup = re.sub(r'<script[^>]*>.*?</script>|<link[^>]*>', '', response.text(), flags=re.S)
                    page.set_content(markup)
                    page.add_style_tag(path=str(ROOT/'public/assets/book.css'))
                    for asset in ['book.js','page-tree.js']:
                        page.add_script_tag(path=str(ROOT/'public/assets'/asset))
                    page.evaluate("""() => { window.treePost = null; document.addEventListener('submit', e => {
                      if (e.defaultPrevented || !e.target.matches('form[action="/studio/tree"]')) return;
                      e.preventDefault(); window.treePost = Object.fromEntries(new FormData(e.target,e.submitter));
                    }, {once:false}); }""")
                def action(callback):
                    if not bridged:
                        with page.expect_navigation(wait_until='domcontentloaded'):
                            callback()
                    else:
                        callback()
                        page.wait_for_function('window.treePost !== null')
                        data = page.evaluate('window.treePost')
                        response = api.post(base+'/studio/tree',form=data,max_redirects=0)
                        assert response.status==303, response.text()
                        load_tree(base+response.headers['location'])
                if bridged:
                    load_tree(base+'/studio/tree')
                else:
                    page.goto(base+'/studio/tree')
                page.locator('[data-tree-ui]').wait_for()
                old = 'handbook/1.0/welcome'; target = 'handbook/1.0/authoring'; new = target+'/welcome'
                handle = page.locator(f'[data-drag-key="{old}"]')
                zone = page.locator(f'[data-drop-key="{target}"][data-drop-position="inside"]')
                # HTML5 drag events are generated by Chromium, not by a mocked handler.
                action(lambda: handle.drag_to(zone))
                check(page.locator(f'[data-tree-node="{new}/child"]').count()==1,'drag-and-drop moves entire branch through PHP')
                public = pw.request.new_context()
                check(public.get(base+'/api/v1/pages/'+old).ok and public.get(base+'/api/v1/pages/'+new).status==404,'drag preserves old public snapshot')
                form = page.locator('[data-tree-form]')
                form.locator('[name=source]').select_option(new)
                form.locator('[name=target]').select_option('handbook/1.0/getting-started')
                form.locator('[name=position]').select_option('before')
                form.locator('[name=slug]').fill('manual')
                action(lambda: form.locator('[value=move]').click())
                final='handbook/1.0/manual'
                check(page.locator(f'[data-tree-node="{final}/child"]').count()==1,'keyboard-accessible form moves and renames branch')
                form=page.locator('[data-tree-form]')
                form.locator('[name=source]').select_option(final)
                form.locator('[name=position]').select_option('root')
                form.locator('[name=slug]').fill('copy')
                action(lambda: form.locator('[value=duplicate]').click())
                check(page.locator('[data-tree-node="handbook/1.0/copy/child"]').count()==1,'duplicate branch through Studio')
                page.once('dialog', lambda dialog: dialog.accept())
                action(lambda: page.get_by_role('button',name='Publish tree').click())
                r=public.get(base+'/api/v1/pages/'+old,max_redirects=0)
                check(r.status==308 and r.headers['location']=='/api/v1/pages/'+final,'published tree activates stable redirects')
                check(public.get(base+'/api/v1/pages/'+final+'/child').ok and public.get(base+'/api/v1/pages/handbook/1.0/copy').status==404,'child public route and duplicate isolation')
                check(not errors,'no Chromium JavaScript exceptions')
                browser.close()
        except Exception:
            log.seek(0)
            print(log.read())
            raise
        finally:
            server.terminate()
            server.wait(timeout=5)
